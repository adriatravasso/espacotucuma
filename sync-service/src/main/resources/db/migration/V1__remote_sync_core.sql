CREATE TABLE estabelecimento_remoto (
    id UUID PRIMARY KEY,
    nome TEXT NOT NULL CHECK (length(trim(nome)) BETWEEN 2 AND 160),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE dispositivo_autorizado (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimento_remoto(id) ON DELETE RESTRICT,
    nome TEXT NOT NULL CHECK (length(trim(nome)) BETWEEN 2 AND 120),
    estado TEXT NOT NULL CHECK (estado IN ('ATIVO', 'REVOGADO')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultimo_acesso_em TIMESTAMPTZ
);

CREATE UNIQUE INDEX uq_dispositivo_ativo_por_estabelecimento
    ON dispositivo_autorizado (estabelecimento_id)
    WHERE estado = 'ATIVO';

CREATE TABLE operacao_recebida (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimento_remoto(id) ON DELETE RESTRICT,
    dispositivo_id UUID NOT NULL REFERENCES dispositivo_autorizado(id) ON DELETE RESTRICT,
    chave_idempotencia TEXT NOT NULL CHECK (length(trim(chave_idempotencia)) BETWEEN 1 AND 160),
    entidade TEXT NOT NULL CHECK (length(trim(entidade)) BETWEEN 1 AND 80),
    entidade_id UUID NOT NULL,
    tipo_operacao TEXT NOT NULL CHECK (length(trim(tipo_operacao)) BETWEEN 1 AND 80),
    payload JSONB NOT NULL,
    payload_versao INTEGER NOT NULL CHECK (payload_versao > 0),
    versao_esperada BIGINT NOT NULL CHECK (versao_esperada >= 0),
    sequencia BIGINT GENERATED BY DEFAULT AS IDENTITY,
    resultado_estado TEXT NOT NULL CHECK (resultado_estado IN ('ACEITA', 'REJEITADA', 'CONFLITO')),
    resultado JSONB NOT NULL DEFAULT '{}'::jsonb,
    recebida_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (estabelecimento_id, chave_idempotencia),
    UNIQUE (estabelecimento_id, sequencia)
);

CREATE INDEX idx_operacao_recebida_dispositivo_sequencia
    ON operacao_recebida (estabelecimento_id, dispositivo_id, sequencia);

CREATE TABLE checkpoint_sincronizacao (
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimento_remoto(id) ON DELETE RESTRICT,
    dispositivo_id UUID NOT NULL REFERENCES dispositivo_autorizado(id) ON DELETE RESTRICT,
    ultima_sequencia BIGINT NOT NULL DEFAULT 0 CHECK (ultima_sequencia >= 0),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (estabelecimento_id, dispositivo_id)
);

CREATE TABLE estado_reconciliado (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimento_remoto(id) ON DELETE RESTRICT,
    dispositivo_id UUID NOT NULL REFERENCES dispositivo_autorizado(id) ON DELETE RESTRICT,
    operacao_id UUID REFERENCES operacao_recebida(id) ON DELETE RESTRICT,
    codigo TEXT NOT NULL CHECK (length(trim(codigo)) BETWEEN 1 AND 80),
    estado TEXT NOT NULL CHECK (estado IN ('ABERTO', 'RESOLVIDO')),
    detalhes JSONB NOT NULL DEFAULT '{}'::jsonb,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolvido_em TIMESTAMPTZ,
    CHECK ((estado = 'ABERTO' AND resolvido_em IS NULL) OR (estado = 'RESOLVIDO' AND resolvido_em IS NOT NULL))
);

CREATE INDEX idx_estado_reconciliado_pendente
    ON estado_reconciliado (estabelecimento_id, criado_em)
    WHERE estado = 'ABERTO';

CREATE TABLE backup_remoto (
    id UUID PRIMARY KEY,
    estabelecimento_id UUID NOT NULL REFERENCES estabelecimento_remoto(id) ON DELETE RESTRICT,
    sequencia BIGINT NOT NULL CHECK (sequencia >= 0),
    chave_armazenamento TEXT NOT NULL CHECK (length(trim(chave_armazenamento)) BETWEEN 1 AND 1024),
    checksum_sha256 CHAR(64) NOT NULL CHECK (checksum_sha256 ~ '^[0-9a-f]{64}$'),
    versao_formato INTEGER NOT NULL CHECK (versao_formato > 0),
    estado TEXT NOT NULL CHECK (estado IN ('PENDENTE', 'VALIDADO', 'FALHOU')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    validado_em TIMESTAMPTZ,
    UNIQUE (estabelecimento_id, chave_armazenamento),
    CHECK ((estado = 'VALIDADO' AND validado_em IS NOT NULL) OR estado <> 'VALIDADO')
);

CREATE INDEX idx_backup_remoto_historico
    ON backup_remoto (estabelecimento_id, criado_em DESC);
